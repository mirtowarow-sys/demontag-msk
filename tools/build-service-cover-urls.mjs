function get(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, { headers: { "user-agent": "Mozilla/5.0 project7053477-scrape" } }, (res) => {
        let data = "";
        res.on("data", (c) => (data += c));
        res.on("end", () => resolve(data));
      })
      .on("error", reject);
  });
}

function pickOg(html) {
  const m1 = html.match(/property\s*=\s*["']og:image["']\s+content\s*=\s*["']([^"']+)["']/i);
  if (m1?.[1]) return m1[1];
  const m2 = html.match(/content\s*=\s*["']([^"']+)["']\s+property\s*=\s*["']og:image["']/i);
  if (m2?.[1]) return m2[1];
  const m3 = [
    ...html.matchAll(
      /https:\/\/(?:static|optim|thb)\.tildacdn\.com[^"'<\s]+\.(?:jpg|jpeg|png|webp)/gi,
    ),
  ];
  return m3[0]?.[0] ?? null;
}

const base = "https://demontagmsk.ru";

const map = {};

for (const slug of canonicalSlugs) {
  const path = `/uslugi/${slug}`;
  const url = `${base}${path}`;
  process.stderr.write(`${path}...\n`);
  const html = await get(url);
  map[slug] = pickOg(html);
}

